import { mkdtemp,mkdir,rm,readFile,writeFile } from 'node:fs/promises';
import { resolve,join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
const repo='/workspace/harness-agent-agent-round2';
const dir=await mkdtemp('/workspace/harness-agent/.ci/agent-round2-20261004/independent-review/candidate-failure-');
const {JsonlCandidateStore,CANDIDATES_FILE_NAME}=await import(pathToFileURL(join(repo,'packages/harness/dist/candidate-store.js')));
const {PostTurnReflector}=await import(pathToFileURL(join(repo,'packages/harness/dist/reflection-runner.js')));
const {JSONLEventStore}=await import(pathToFileURL(join(repo,'packages/events/dist/event-store.js')));
const store=new JsonlCandidateStore({dataDir:dir}),events=new JSONLEventStore({dataDir:join(dir,'events')});
const reflector=new PostTurnReflector({candidateStore:store,events,dataDir:dir});
const sessionId='session_independent',turnId='turn_independent';
await events.appendNew({id:'event_start',sessionId,turnId,type:'turn.started',timestamp:1,payload:{turnId}});
await events.appendNew({id:'event_failure',sessionId,turnId,type:'verification.failed',timestamp:2,payload:{error:'failed check'}});
await events.appendNew({id:'event_terminal',sessionId,turnId,type:'turn.failed',timestamp:3,payload:{turnId,error:{code:'VERIFICATION_FAILED',message:'failed check'}}});
await store.list();
await mkdir(join(dir,CANDIDATES_FILE_NAME));
const result=await reflector.reflect({sessionId,turnId,outcome:{status:'failed'}});
const queuedAfterFailure=await store.list();
await rm(join(dir,CANDIDATES_FILE_NAME),{recursive:true});
const freshQueue=await new JsonlCandidateStore({dataDir:dir}).list();
const journal=await reflector.listJournal();
const fingerprints={};
for(const p of ['packages/harness/src/candidate-store.ts','packages/harness/dist/candidate-store.js','packages/harness/src/reflection-runner.ts','packages/harness/dist/reflection-runner.js'])fingerprints[p]=createHash('sha256').update(await readFile(join(repo,p))).digest('hex');
const receipt={stage:'Independent actual filesystem probe; existing candidate-store failure/cache semantics, no model calls',result,journalRows:journal.length,sameInstanceQueueRows:queuedAfterFailure.length,freshQueueRows:freshQueue.length,sourceFingerprints:fingerprints,paidCalls:0,queueCandidates:queuedAfterFailure};
await writeFile('/workspace/harness-agent/.ci/agent-round2-20261004/independent-review/candidate-failure-review.json',JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify({result,journalRows:journal.length,sameInstanceQueueRows:queuedAfterFailure.length,freshQueueRows:freshQueue.length}));
